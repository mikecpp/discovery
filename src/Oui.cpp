std::string Oui::vendor(const std::string& mac) {
    const std::string digits = normalize(mac);
    if (digits.size() < 6) {
        return {};
    }
    if (digits.compare(0, 4, "0242") == 0) {
        return "Docker";
    }
    if (isRandomized(mac)) {
        return "Private (randomized)";
    }
    const std::string prefix = digits.substr(0, 6);
    for (const Entry& entry : kEntries) {
        if (normalize(entry.prefix) == prefix) {
            return entry.vendor;
        }
    }
    return {};
}

bool Oui::isRandomized(const std::string& mac) {
    const std::string digits = normalize(mac);
    if (digits.size() < 2) {
        return false;
    }
    const char second = digits[1];
    return second == '2' || second == '6' || second == 'A' || second == 'E';
}
