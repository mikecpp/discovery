std::string normalize(const std::string& mac) {
    std::string result;
    for (const char character : mac) {
        if (std::isxdigit(static_cast<unsigned char>(character)) != 0) {
            result += static_cast<char>(std::toupper(static_cast<unsigned char>(character)));
        }
    }
    return result;
}

